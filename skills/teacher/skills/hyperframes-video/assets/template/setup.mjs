#!/usr/bin/env node
// setup.mjs: copy GSAP, its plugins and the fonts out of node_modules into vendor/, where index.html loads them.
// Runs on `npm install` (postinstall) and is safe to re-run. HyperFrames serves the project folder as-is, so every
// file the page loads has to live inside it: no CDN (offline renders), no Google Fonts (blocked in the sandbox).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const nm = path.join(here, 'node_modules');
const copies = [
  ...['gsap', 'DrawSVGPlugin', 'MotionPathPlugin', 'SplitText', 'TextPlugin', 'CustomEase'].map((n) => [`gsap/dist/${n}.min.js`, `js/${n}.min.js`]),
  ...[400, 500, 600, 700, 800, 900].map((w) => [`@fontsource/inter/files/inter-latin-${w}-normal.woff2`, `fonts/inter-${w}.woff2`]),
  ...[400, 500, 700].map((w) => [`@fontsource/jetbrains-mono/files/jetbrains-mono-latin-${w}-normal.woff2`, `fonts/jbm-${w}.woff2`]),
  ['@fontsource/bangers/files/bangers-latin-400-normal.woff2', 'fonts/bangers-400.woff2'],
];
let n = 0;
for (const [from, to] of copies) {
  const src = path.join(nm, from), dst = path.join(here, 'vendor', to);
  if (!fs.existsSync(src)) { console.error(`setup: missing ${from}; run npm install`); process.exit(1); }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  if (!fs.existsSync(dst) || fs.statSync(dst).size !== fs.statSync(src).size) { fs.copyFileSync(src, dst); n++; }
}
// vendor/fonts.css: @font-face rules for the copied files. Paths are relative to vendor/ (HyperFrames' linter
// rejects "../" in asset paths). The latin subsets lack arrows and maths symbols (→ ∞ ≤): the font stacks in
// kit/tokens.js fall back to system Inter / Inter Display / DejaVu for those glyphs.
const face = (fam, w, file) => `@font-face { font-family: "${fam}"; font-weight: ${w}; font-display: block; src: url("fonts/${file}") format("woff2"); }`;
const css = [
  '/* generated by setup.mjs: local fonts (Google Fonts is blocked in the sandbox; renders must work offline) */',
  ...[400, 500, 600, 700, 800, 900].map((w) => face('InterLocal', w, `inter-${w}.woff2`)),
  ...[400, 500, 700].map((w) => face('JBM', w, `jbm-${w}.woff2`)),
  face('Bangers', 400, 'bangers-400.woff2'),
].join('\n') + '\n';
fs.writeFileSync(path.join(here, 'vendor', 'fonts.css'), css);
console.log(`setup: vendor/ ready (${copies.length} files, ${n} copied, fonts.css written)`);
