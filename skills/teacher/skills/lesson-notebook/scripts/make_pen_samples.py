#!/usr/bin/env python3
"""Embed the pen recordings in assets/sounds/ as base64 in assets/pen-samples.js.

  python3 make_pen_samples.py [--check]

The bundler inlines pen-samples.js like any other module, so a lesson stays
one self-contained file. --check exits 1 if the embedded copy is stale.
"""

from __future__ import annotations

import base64
import sys
from pathlib import Path

ASSETS = Path(__file__).resolve().parent.parent / "assets"
SOUNDS = ASSETS / "sounds"
OUT = ASSETS / "pen-samples.js"
KINDS = {"chalk": ["chalk-1.mp3", "chalk-2.mp3"], "paper": ["pencil.mp3"]}


def render() -> str:
    lines = [
        "// Generated by scripts/make_pen_samples.py from assets/sounds/ (CC0 recordings,",
        "// see sounds/SOUNDS.md). Don't edit by hand.",
        "export const PEN_SAMPLES = {",
    ]
    for kind, files in KINDS.items():
        lines.append(f"  {kind}: [")
        for name in files:
            data = base64.b64encode((SOUNDS / name).read_bytes()).decode()
            lines.append(f'    "{data}",')
        lines.append("  ],")
    lines.append("};")
    return "\n".join(lines) + "\n"


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("pen-samples.js is up to date" if ok else "pen-samples.js is stale: run make_pen_samples.py")
        return 0 if ok else 1
    OUT.write_text(text)
    print(f"wrote {OUT.name} ({len(text) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
